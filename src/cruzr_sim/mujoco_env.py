"""MuJoCo 版 Cruzr S2 会话：把仿真包成 Show-Harness 认识的那 4 个方法。

Show-Harness 的真机抽象层只要 4 个方法（get_ee_pose / get_gripper_position /
control_gripper / update_desired_ee_pose）+ 一个 get_observation 的 session。
真机上是优必选 SDK 实现这四个；这里是 MuJoCo + DLS IK 的参考实现（未验证真机等价性），
本仓库仅提取仿真底座；原 Show-Harness 控制器、插件和安全钳制不包含在本包中。

与真机的对应关系：
    FrankaSession.robot.update_desired_ee_pose  ->  运控板 /mc/sdk/robot_command
    本文件.update_desired_ee_pose               ->  sim/ik.py 解 IK -> 关节位置伺服
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import numpy as np

if sys.platform.startswith("linux"):
    os.environ.setdefault("MUJOCO_GL", "egl")

import mujoco  # noqa: E402

from cruzr_sim.ik import ArmIK  # noqa: E402
from cruzr_sim.scene import (  # noqa: E402
    ARM_JOINTS,
    HOME_L,
    HOME_R,
    TIP_OFFSET,
    fingers,
    gripper_origin,
    gripper_tip,
    reset_home,
)

XML = str(Path(os.environ.get("CRUZR_MODEL_PATH", Path(__file__).resolve().parents[2] / "models" / "cruzr_s2" / "scene.xml")))
OPEN_WIDTH_M = 0.045
CLOSED_WIDTH_M = 0.004
# Finger joint coordinates are measured from the vendor URDF zero pose.  Both
# joints move inward for positive q.  The slim collision proxies generated by
# tools/urdf2mjcf.py have 6 mm half-thickness on the closing axis.
OPEN_FINGER_Q = -0.012
CLOSED_FINGER_Q = 0.008
FINGER_ZERO_GAP_M = 0.0205


class MujocoCruzrRobot:
    """四个 duck-type 方法 + 仿真驱动。"""

    def __init__(self, side: str = "R", render_size: int = 256, verbose: bool = True):
        if side not in ("L", "R"):
            raise ValueError("side must be L or R")
        if not Path(XML).is_file():
            raise FileNotFoundError("Robot model missing. Run scripts/import_assets.py --source-root PATH; see models/README.md")
        self.side = side
        self.verbose = verbose
        self.render_size = render_size
        self.model = mujoco.MjModel.from_xml_path(XML)
        self.data = mujoco.MjData(self.model)
        reset_home(self.model, self.data)
        mujoco.mj_forward(self.model, self.data)
        self.ik = ArmIK(self.model, self.data, side)
        self._renderer = None
        self._closed = False
        # The two local +Z axes map to opposite world directions because the
        # finger bodies have mirrored rotations.  Store actuator + joint pairs
        # so width is read from physics instead of a command-state flag.
        self._finger_act = []
        for k in (1, 2):
            aid = mujoco.mj_name2id(
                self.model, mujoco.mjtObj.mjOBJ_ACTUATOR, f"act_{side}_finger{k}_joint"
            )
            jid = mujoco.mj_name2id(
                self.model, mujoco.mjtObj.mjOBJ_JOINT, f"{side}_finger{k}_joint"
            )
            if aid >= 0 and jid >= 0:
                self._finger_act.append((aid, jid))
        self._arm_act = {}
        for comp in ARM_JOINTS:
            name = f"{side}_{comp}_joint"
            aid = mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_ACTUATOR, f"act_{name}")
            jid = mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_JOINT, name)
            if aid >= 0 and jid >= 0:
                self._arm_act[comp] = (aid, jid)
        # reset_home sets qpos but MuJoCo position actuators default to ctrl=0.
        # Without synchronising ctrl, the first gripper command advances time
        # and silently drags the whole arm toward its zero pose.
        for aid, jid in self._arm_act.values():
            self.data.ctrl[aid] = self.data.qpos[self.model.jnt_qposadr[jid]]
        for aid, jid in self._finger_act:
            self.data.qpos[self.model.jnt_qposadr[jid]] = OPEN_FINGER_Q
            self.data.ctrl[aid] = OPEN_FINGER_Q
        mujoco.mj_forward(self.model, self.data)
        if self.verbose:
            print(f"[mujoco] Cruzr S2 载入完成 臂={side} nq={self.model.nq} nu={self.model.nu}")

    # ------------------------------------------------------------ 4 个方法
    def get_ee_pose(self):
        """末端位姿 [x, y, z, qw, qx, qy, qz]（夹爪基座，世界系）。"""
        pos, rot = gripper_origin(self.model, self.data, self.side)
        quat = _rot_to_quat(rot)
        return [float(pos[0]), float(pos[1]), float(pos[2]),
                float(quat[0]), float(quat[1]), float(quat[2]), float(quat[3])]

    def get_gripper_position(self):
        """Return the physical inner aperture in metres.

        With an object between the fingers the joints stop before the commanded
        closed target, so this measurement also exposes a successful grasp to
        the recovery plugin (just like ``GripStatus.pos`` on the real robot).
        """
        if not self._finger_act:
            return [float(CLOSED_WIDTH_M if self._closed else OPEN_WIDTH_M)]
        travel = sum(
            float(self.data.qpos[self.model.jnt_qposadr[jid]])
            for _, jid in self._finger_act
        )
        width = np.clip(FINGER_ZERO_GAP_M - travel, 0.0, OPEN_WIDTH_M)
        return [float(width)]

    def control_gripper(self, close: bool):
        self._closed = bool(close)
        target = CLOSED_FINGER_Q if close else OPEN_FINGER_Q
        for aid, _ in self._finger_act:
            self.data.ctrl[aid] = target
        for _ in range(180):
            mujoco.mj_step(self.model, self.data)
        return self.get_gripper_position()[0]

    def update_desired_ee_pose(self, pose7):
        """笛卡尔目标 -> IK -> 关节位置伺服 -> 仿真推进到收敛。"""
        target = np.asarray(pose7, dtype=float)
        if target.shape[0] < 7:
            raise ValueError("update_desired_ee_pose expects [x,y,z,qw,qx,qy,qz]")
        rot = _quat_to_rot(target[3:7])
        q, pos_err, rot_err = self.ik.solve(
            target[0:3], rot, iters=220, damp=0.10, step=0.6, tol=2e-3
        )
        # A direct position-target step creates an impulse strong enough to
        # eject a grasped cube when the arm gains are high enough to resist
        # gravity.  Interpolate with a zero-slope smoothstep, then settle.
        q_start = np.array([
            self.data.qpos[self.model.jnt_qposadr[self._arm_act[comp][1]]]
            for comp in ARM_JOINTS
        ])
        for k in range(1, 121):
            alpha = k / 120.0
            blend = alpha * alpha * (3.0 - 2.0 * alpha)
            q_cmd = q_start + blend * (q - q_start)
            for i, comp in enumerate(ARM_JOINTS):
                aid, _ = self._arm_act[comp]
                self.data.ctrl[aid] = float(q_cmd[i])
            mujoco.mj_step(self.model, self.data)
        for _ in range(60):
            mujoco.mj_step(self.model, self.data)
        if self.verbose and (pos_err > 0.02 or rot_err > 0.2):
            print(f"[mujoco] IK 残差大: pos {pos_err*1000:.0f} mm, rot {np.degrees(rot_err):.1f} deg")
        return pos_err

    # ------------------------------------------------------------ 相机
    def _render(self, camera: str):
        if self._renderer is None:
            self._renderer = mujoco.Renderer(self.model, 480, 640)
        cid = mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_CAMERA, camera)
        self._renderer.update_scene(self.data, camera=cid)
        img = self._renderer.render()
        if self.render_size and img.shape[0] != self.render_size:
            import cv2

            img = cv2.resize(img, (self.render_size, self.render_size))
        return img

    def camera_frames(self):
        return self._render("front_cam"), self._render(f"{self.side}_wrist_cam")

    def fingers_tip(self):
        return gripper_tip(self.model, self.data, self.side)

    def close(self):
        if self._renderer is not None:
            self._renderer.close()
            self._renderer = None


class MujocoCruzrSession:
    """Show-Harness 的 session 契约：connect / close / get_observation / get_camera_frames。"""

    def __init__(self, side: str = "R", render_size: int = 256, verbose: bool = True):
        self.robot = MujocoCruzrRobot(side=side, render_size=render_size, verbose=verbose)
        self._connected = False
        self.verbose = verbose

    def connect(self):
        self._connected = True
        if self.verbose:
            print("[mujoco] session connected")

    def close(self):
        self.robot.close()
        self._connected = False

    def get_camera_frames(self):
        return self.robot.camera_frames()

    def get_observation(self) -> dict:
        if not self._connected:
            raise RuntimeError("get_observation called before connect()")
        agentview, wrist = self.robot.camera_frames()
        return {
            "agentview": agentview,
            "wrist": wrist,
            "ee_pose": np.asarray(self.robot.get_ee_pose(), dtype=float),
            "gripper_width": float(self.robot.get_gripper_position()[0]),
        }


# ---------------------------------------------------------------- 四元数工具


def _rot_to_quat(R) -> np.ndarray:
    tr = float(np.trace(R))
    if tr > 0:
        s = np.sqrt(tr + 1.0) * 2
        w = 0.25 * s
        x = (R[2, 1] - R[1, 2]) / s
        y = (R[0, 2] - R[2, 0]) / s
        z = (R[1, 0] - R[0, 1]) / s
    elif R[0, 0] > R[1, 1] and R[0, 0] > R[2, 2]:
        s = np.sqrt(1.0 + R[0, 0] - R[1, 1] - R[2, 2]) * 2
        w = (R[2, 1] - R[1, 2]) / s
        x = 0.25 * s
        y = (R[0, 1] + R[1, 0]) / s
        z = (R[0, 2] + R[2, 0]) / s
    elif R[1, 1] > R[2, 2]:
        s = np.sqrt(1.0 + R[1, 1] - R[0, 0] - R[2, 2]) * 2
        w = (R[0, 2] - R[2, 0]) / s
        x = (R[0, 1] + R[1, 0]) / s
        y = 0.25 * s
        z = (R[1, 2] + R[2, 1]) / s
    else:
        s = np.sqrt(1.0 + R[2, 2] - R[0, 0] - R[1, 1]) * 2
        w = (R[1, 0] - R[0, 1]) / s
        x = (R[0, 2] + R[2, 0]) / s
        y = (R[1, 2] + R[2, 1]) / s
        z = 0.25 * s
    q = np.array([w, x, y, z])
    return q / np.linalg.norm(q)


def _quat_to_rot(q) -> np.ndarray:
    w, x, y, z = np.asarray(q, dtype=float)
    n = np.linalg.norm([w, x, y, z])
    w, x, y, z = w / n, x / n, y / n, z / n
    return np.array([
        [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
        [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
        [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)],
    ])
